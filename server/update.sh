#!/usr/bin/env bash
#
# update.sh -- apply a new Movinite (media-server) release to a server that ALREADY has it installed.
#
#     cd /opt/media-server
#     sudo bash update.sh /path/to/media-server-ver1.1.tar.gz     # apply an update
#     sudo bash update.sh                                          # newest media-server-ver*.tar.gz found
#                                                                  #   next to this folder or in the current dir
#     sudo bash update.sh --rollback backups/media-server-pre-1.1-20261123-154500.tgz
#
#   A copy of update.sh kept next to the tarballs (outside /opt/media-server) hands over to the installed
#   /opt/media-server/update.sh with the newest tarball in its folder.
#
# What it does, in order:
#   1. unpacks the tarball to a temp dir and refuses one that is not Media Server, or is older than
#      (or the same as) what is installed (override with --force)
#   2. BACKS UP first: code + .env + a consistent snapshot of data/media-server.db (sqlite backup API)
#      -> backups/media-server-pre-<newver>-<time>.tgz   (newest 10 kept; thumbnails are not backed up,
#      they are regenerated by a scan)
#   3. stops the service, mirrors the new code in (rsync --delete) -- .env, data/, backups/, .venv and
#      ADMIN_PASSWORD are never touched
#   4. updates Python dependencies, re-installs the share mount helper + sudoers rule, runs the
#      idempotent database upgrade, starts the service and checks it serves the NEW version.
#      1.5.2: if hardware transcoding was never set up, it scans for a video card, installs its drivers,
#      tests it and saves the result; a value already saved (by install or in Settings) is always kept.
#      If anything fails after the mirror, the previous code is restored from the backup automatically.
#      2.0: before the schema 11 upgrade it also saves a checked copy of the database as
#      data/media-server.db.pre-schema11 (mode 600).
#
# Your .env, database, users, libraries, watch progress and mounted shares are preserved.
#
# New SYSTEM packages (apt) are not installed here; if a release needs one, its CHANGELOG entry says so --
# re-run install.sh (it is safe to re-run).
# shellcheck disable=SC2015
set -Eeuo pipefail

APP_NAME="media-server"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KEEP_BACKUPS=10
FORCE="no"; ROLLBACK=""; TARBALL_ARG=""
SYSTEMCTL="${MS_SYSTEMCTL:-systemctl}"
HELPER_DST="/usr/local/sbin/media-server-mount"

say() { printf "\n\033[1;36m==> %s\033[0m\n" "$1"; }
ok()  { printf "    \033[32mOK\033[0m  %s\n" "$1"; }
die() { printf "\n\033[31mFAILED: %s\033[0m\n" "$1" >&2; exit 1; }

ORIG_ARGS=("$@")
while [ $# -gt 0 ]; do
  case "$1" in
    --force) FORCE="yes" ;;
    --rollback) ROLLBACK="${2:?--rollback needs a backup file}"; shift ;;
    -h|--help) awk 'NR>1 && /^#/ && !/shellcheck/ {sub(/^# ?/,""); print; next} NR>1 {exit}' "${BASH_SOURCE[0]}"; exit 0 ;;
    -*) die "Unknown option: $1" ;;
    *) TARBALL_ARG="$1" ;;
  esac
  shift
done
# resolve relative paths BEFORE we change directory
case "${TARBALL_ARG:-.}" in /*|.) : ;; *) TARBALL_ARG="$PWD/$TARBALL_ARG" ;; esac
case "${ROLLBACK:-.}" in /*|.) : ;; *) ROLLBACK="$PWD/$ROLLBACK" ;; esac
CALLER_PWD="$PWD"

if [ "$(id -u)" -ne 0 ] && [ "${MS_UPDATE_NOROOT:-}" != "1" ]; then
  command -v sudo >/dev/null 2>&1 || die "Run as root (the service, backups and file ownership need it)."
  exec sudo -E bash "$0" "${ORIG_ARGS[@]}"
fi
cd "$PROJECT_DIR"
# Bootstrap: update.sh run from outside an installation (e.g. the folder holding the tarballs) ->
# hand over to the installed copy in /opt/media-server, passing the tarball along.
if [ ! -f main.py ] && [ -x /opt/media-server/.venv/bin/python ] && [ -f /opt/media-server/update.sh ]; then
  if [ -z "$TARBALL_ARG" ] && [ -z "$ROLLBACK" ]; then
    # shellcheck disable=SC2012
    TARBALL_ARG="$(ls -1 "$PROJECT_DIR"/media-server-ver*.tar.gz "$CALLER_PWD"/media-server-ver*.tar.gz 2>/dev/null | sort -V | tail -1 || true)"
  fi
  ARGS=(); [ "$FORCE" = "yes" ] && ARGS+=(--force)
  if [ -n "$ROLLBACK" ]; then ARGS+=(--rollback "$ROLLBACK"); elif [ -n "$TARBALL_ARG" ]; then ARGS+=("$TARBALL_ARG"); fi
  exec bash /opt/media-server/update.sh "${ARGS[@]}"
fi
[ -d .venv ] && [ -f main.py ] || die "No .venv/main.py here -- Media Server is not installed in $PROJECT_DIR. Run install.sh first."
VENV_PY="$PROJECT_DIR/.venv/bin/python"
SVC_USER="$("$SYSTEMCTL" cat "${APP_NAME}.service" 2>/dev/null | sed -n 's/^User=//p' | head -1)"
SVC_USER="${SVC_USER:-media-server}"; id "$SVC_USER" >/dev/null 2>&1 || SVC_USER=""
[ "${MS_UPDATE_NOROOT:-}" = "1" ] && SVC_USER=""
have_service() { [ -d /run/systemd/system ] && "$SYSTEMCTL" cat "${APP_NAME}.service" >/dev/null 2>&1; }
ver_of() { sed -n 's/^__version__ *= *"\(.*\)"/\1/p' "$1/app/version.py" 2>/dev/null; }
# integer compare of "1.10" vs "1.9":  prints -1, 0 or 1
vcmp() { python3 - "$1" "$2" <<'PY'
import sys
a=[int(x) for x in sys.argv[1].split(".")]; b=[int(x) for x in sys.argv[2].split(".")]
n=max(len(a),len(b)); a+= [0]*(n-len(a)); b+= [0]*(n-len(b))
print((a>b)-(a<b))
PY
}
app_port() {
  local port
  port="$("$SYSTEMCTL" cat "${APP_NAME}.service" 2>/dev/null | sed -n 's/.*--port \([0-9]*\).*/\1/p' | head -1)"
  echo "${port:-8099}"
}
health_wait() {
  local out
  for _ in $(seq 1 30); do
    sleep 1
    out="$(curl -fsS "http://127.0.0.1:$(app_port)/api/health" 2>/dev/null)" && { echo "$out"; return 0; }
  done
  return 1
}
run_as() { if [ -n "$SVC_USER" ]; then runuser -u "$SVC_USER" -- "$@"; else "$@"; fi; }

# rsync the code from $1 into PROJECT_DIR, never touching local state
mirror_code() {
  rsync -a --checksum --delete \
    --exclude '/.env' --exclude '/data/' --exclude '/backups/' --exclude '/.venv/' --exclude '/ADMIN_PASSWORD' \
    --exclude '__pycache__/' "$1"/ "$PROJECT_DIR"/
  chown -R root:root "$PROJECT_DIR/app" "$PROJECT_DIR/helpers" 2>/dev/null || true
}

system_bits() {
  # mount helper + sudoers (the helper may have changed in this release)
  if [ -n "$SVC_USER" ] && [ -f "$PROJECT_DIR/helpers/media-server-mount" ]; then
    install -o root -g root -m 0755 "$PROJECT_DIR/helpers/media-server-mount" "$HELPER_DST"
    local t; t="$(mktemp)"
    printf '# Media Server: the service may run ONLY the share mount helper as root\n%s ALL=(root) NOPASSWD: %s\n' "$SVC_USER" "$HELPER_DST" > "$t"
    if visudo -cf "$t" >/dev/null 2>&1; then install -o root -g root -m 0440 "$t" /etc/sudoers.d/media-server; fi
    rm -f "$t"
  fi
  # 1.4.14: smbclient lets Add library -> Browse list SMB shares and folders without mounting (optional;
  # without it Browse falls back to a short temporary mount). Best effort, never fails the update.
  if ! command -v smbclient >/dev/null 2>&1 && command -v apt-get >/dev/null 2>&1 && [ "${MS_SKIP_APT:-}" != "1" ]; then
    if DEBIAN_FRONTEND=noninteractive timeout 300 apt-get install -y -q smbclient >/dev/null 2>&1; then
      ok "smbclient installed (for browsing SMB shares in Add library)"
    else
      printf "    \033[33mWARN\033[0m %s\n" "could not install smbclient -- Browse will use a temporary mount instead (sudo apt install smbclient)"
    fi
  fi
}

restart_and_check() {
  local want="$1" out served
  if have_service; then
    "$SYSTEMCTL" restart "$APP_NAME"
    if out="$(health_wait)"; then
      served="$(echo "$out" | python3 -c 'import sys,json; print(json.load(sys.stdin).get("version",""))' 2>/dev/null)"
      echo "    Movinite is up: $out"
      [ -z "$want" ] || [ "$served" = "$want" ] || { echo "    serving v$served but v$want is on disk"; return 1; }
      return 0
    fi
    echo "    Movinite did not answer within 30 s.  journalctl -u ${APP_NAME} -e"
    return 1
  fi
  echo "    (no systemd service here -- start it by hand: .venv/bin/uvicorn main:app --host 0.0.0.0 --port 8099)"
  return 0
}

backup_now() {
  # $1 = label (new version).  Writes backups/media-server-pre-<label>-<time>.tgz, prints its path.
  local label="$1" stamp tmp out
  stamp="$(date +%Y%m%d-%H%M%S)"
  mkdir -p "$PROJECT_DIR/backups"
  out="$PROJECT_DIR/backups/media-server-pre-${label}-${stamp}.tgz"
  tmp="$(mktemp -d)"
  mkdir -p "$tmp/code" "$tmp/data"
  rsync -a --exclude '/data/' --exclude '/backups/' --exclude '/.venv/' --exclude '__pycache__/' "$PROJECT_DIR"/ "$tmp/code"/
  if [ -f "$PROJECT_DIR/data/media-server.db" ]; then
    python3 - "$PROJECT_DIR/data/media-server.db" "$tmp/data/media-server.db" <<'PY'
import sqlite3, sys
src = sqlite3.connect(sys.argv[1], timeout=60); dst = sqlite3.connect(sys.argv[2])
with dst: src.backup(dst)
dst.close(); src.close()
PY
  fi
  # 1.9: the server key and the encrypted Gmail tokens (data/secrets, 0700/0600) go in the backup too,
  # so a rollback keeps the Gmail connection. The tarball itself is mode 600.
  if [ -d "$PROJECT_DIR/data/secrets" ]; then
    cp -a "$PROJECT_DIR/data/secrets" "$tmp/data/secrets"
  fi
  tar -czf "$out" -C "$tmp" code data
  rm -rf "$tmp"
  chmod 600 "$out"
  # keep the newest $KEEP_BACKUPS
  # shellcheck disable=SC2012
  ls -1t "$PROJECT_DIR"/backups/media-server-pre-*.tgz 2>/dev/null | tail -n +$((KEEP_BACKUPS + 1)) | xargs -r rm -f
  echo "$out"
}

# ---------------------------------------------------------------------------
# rollback
# ---------------------------------------------------------------------------
if [ -n "$ROLLBACK" ]; then
  [ -f "$ROLLBACK" ] || die "Backup not found: $ROLLBACK"
  say "Rolling back to $(basename "$ROLLBACK")"
  TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
  tar -xzf "$ROLLBACK" -C "$TMP"
  [ -f "$TMP/code/app/version.py" ] || die "That file is not a Media Server backup."
  OLD="$(ver_of "$TMP/code")"
  SAFETY="$(backup_now "rollback-from-$(ver_of "$PROJECT_DIR")")"
  echo "    current state saved first: $SAFETY"
  have_service && "$SYSTEMCTL" stop "$APP_NAME" || true
  mirror_code "$TMP/code"
  [ -f "$TMP/code/.env" ] && cp -p "$TMP/code/.env" "$PROJECT_DIR/.env"
  if [ -f "$TMP/data/media-server.db" ]; then
    rm -f "$PROJECT_DIR"/data/media-server.db-wal "$PROJECT_DIR"/data/media-server.db-shm
    cp "$TMP/data/media-server.db" "$PROJECT_DIR/data/media-server.db"
    [ -n "$SVC_USER" ] && chown "$SVC_USER:$SVC_USER" "$PROJECT_DIR/data/media-server.db"
  fi
  if [ -d "$TMP/data/secrets" ]; then        # 1.9+: restore the server key + sealed tokens with the database
    rm -rf "$PROJECT_DIR/data/secrets"
    cp -a "$TMP/data/secrets" "$PROJECT_DIR/data/secrets"
    chmod 700 "$PROJECT_DIR/data/secrets"; chmod 600 "$PROJECT_DIR"/data/secrets/* 2>/dev/null || true
    [ -n "$SVC_USER" ] && chown -R "$SVC_USER:$SVC_USER" "$PROJECT_DIR/data/secrets"
  fi
  "$VENV_PY" -m pip install --quiet -r "$PROJECT_DIR/requirements.txt" || true
  system_bits
  restart_and_check "$OLD" || die "rolled back, but the service did not come up -- journalctl -u $APP_NAME -e"
  say "Rolled back to v$OLD (database restored from the backup)"
  exit 0
fi

# ---------------------------------------------------------------------------
# find + check the tarball
# ---------------------------------------------------------------------------
if [ -z "$TARBALL_ARG" ]; then
  # shellcheck disable=SC2012
  TARBALL_ARG="$(ls -1 "$CALLER_PWD"/media-server-ver*.tar.gz "$(dirname "$PROJECT_DIR")"/media-server-ver*.tar.gz 2>/dev/null \
                 | sort -V | tail -1 || true)"
  [ -n "$TARBALL_ARG" ] || die "No tarball given and no media-server-ver*.tar.gz found.  Usage: sudo bash update.sh /path/to/media-server-verX.Y.tar.gz"
  echo "Using newest tarball found: $TARBALL_ARG"
fi
[ -f "$TARBALL_ARG" ] || die "Tarball not found: $TARBALL_ARG"
if [ -f "$TARBALL_ARG.sha256" ]; then
  ( cd "$(dirname "$TARBALL_ARG")" && sha256sum -c "$(basename "$TARBALL_ARG").sha256" >/dev/null ) || die "SHA-256 check failed for $TARBALL_ARG"
  ok "checksum verified ($TARBALL_ARG.sha256)"
fi
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
tar -xzf "$TARBALL_ARG" -C "$TMP" || die "Could not unpack $TARBALL_ARG"
NEW_DIR="$TMP/media-server"
[ -f "$NEW_DIR/app/version.py" ] && [ -f "$NEW_DIR/main.py" ] || die "$TARBALL_ARG is not a Media Server release (no media-server/app/version.py)."
CUR="$(ver_of "$PROJECT_DIR")"; NEW="$(ver_of "$NEW_DIR")"
[ -n "$NEW" ] || die "cannot read the version in the tarball"
echo "Installed: v${CUR:-?}    Tarball: v$NEW"
if [ -n "$CUR" ] && [ "$FORCE" != "yes" ]; then
  c="$(vcmp "$NEW" "$CUR")"
  [ "$c" = "1" ] || die "v$NEW is not newer than the installed v$CUR (use --force to re-apply or downgrade)."
fi

# ---------------------------------------------------------------------------
# backup, mirror, migrate, restart
# ---------------------------------------------------------------------------
say "Backing up the current version"
BACKUP="$(backup_now "$NEW")"
ok "backup: $BACKUP"

restore_previous() {
  trap - ERR
  set +e
  echo ""
  echo "Something failed -- restoring the previous code (v$CUR) from the backup..."
  local r; r="$(mktemp -d)"
  tar -xzf "$BACKUP" -C "$r"
  mirror_code "$r/code"
  rm -rf "$r"
  "$VENV_PY" -m pip install --quiet -r "$PROJECT_DIR/requirements.txt" || true
  system_bits
  restart_and_check "$CUR" || true
  echo "Previous version restored. Your data was not changed by the failed update."
  echo "To roll back the database as well:  sudo bash $PROJECT_DIR/update.sh --rollback $BACKUP"
}

say "Stopping $APP_NAME"
have_service && "$SYSTEMCTL" stop "$APP_NAME" || true
trap 'restore_previous; rm -rf "$TMP"; exit 1' ERR

say "Installing v$NEW code"
mirror_code "$NEW_DIR"
chmod +x "$PROJECT_DIR"/*.sh "$PROJECT_DIR/helpers/media-server-mount" 2>/dev/null || true
ok "code mirrored (your .env, data/, backups/ and .venv untouched)"

say "Python dependencies"
"$VENV_PY" -m pip install --quiet -r "$PROJECT_DIR/requirements.txt"
"$VENV_PY" -c 'import cryptography' 2>/dev/null || printf "    \033[33mWARN\033[0m %s\n" "python 'cryptography' did not install -- Connect Gmail is unavailable until it does (pip needs pypi.org)"
ok "dependencies up to date"

system_bits
mkdir -p "$PROJECT_DIR/data/thumbs" "$PROJECT_DIR/data/transcode" "$PROJECT_DIR/data/prefetch" "$PROJECT_DIR/data/subs" \
         "$PROJECT_DIR/data/offline"
[ -n "$SVC_USER" ] && chown -R "$SVC_USER:$SVC_USER" "$PROJECT_DIR/data"

# 2.0: a separate, checked snapshot of the database before schema 11 (devices, offline downloads),
# data/media-server.db.pre-schema11 (mode 600), in addition to the full backup tarball above.
# If the snapshot can't be made or doesn't pass an integrity check, the update stops and the previous code comes back.
db_snapshot_before() {
  local want="$1" db="$PROJECT_DIR/data/media-server.db" dest
  dest="$PROJECT_DIR/data/media-server.db.pre-schema${want}"
  [ -f "$db" ] || return 0
  [ -f "$dest" ] && { ok "database snapshot already there: $dest"; return 0; }
  python3 - "$db" "$dest" "$want" <<'PY'
import os, sqlite3, sys
src_p, dest, want = sys.argv[1], sys.argv[2], int(sys.argv[3])
src = sqlite3.connect(src_p, timeout=60)
try:
    cur = int((src.execute("SELECT value FROM meta WHERE key='schema_version'").fetchone() or ["0"])[0])
except sqlite3.Error:
    cur = 0
if cur >= want:
    print("schema %d already" % cur)
    sys.exit(0)
tmp = dest + ".tmp"
if os.path.exists(tmp):
    os.unlink(tmp)
old = os.umask(0o077)
dst = sqlite3.connect(tmp)
with dst:
    src.backup(dst)
ok = dst.execute("PRAGMA integrity_check").fetchone()[0]
dst.close(); src.close()
os.umask(old)
if ok != "ok":
    os.unlink(tmp)
    sys.exit("integrity check failed: %s" % ok)
os.chmod(tmp, 0o600)
os.replace(tmp, dest)
print("saved schema %d snapshot" % cur)
PY
  [ -f "$dest" ] && { [ -n "$SVC_USER" ] && chown "$SVC_USER:$SVC_USER" "$dest"; ok "database backup before schema ${want}: $dest"; }
  return 0
}
say "Database backup before schema 11"
db_snapshot_before 11

# 1.7.9: migrate() also writes data/media-server.db.pre-schema9 (mode 600) before the new
# subtitle / prefetch / probe-cache tables. The tarball above already has a full DB snapshot.
# 1.9: likewise data/media-server.db.pre-schema10 before roles, invites, activity and hashed sessions.
# 2.0: the pre-schema11 snapshot was already made (and checked) by db_snapshot_before above.
say "Database upgrade"
( cd "$PROJECT_DIR" && run_as "$VENV_PY" -m app.cli init ) | grep -E '^database:' | sed 's/^/    /'
find "$PROJECT_DIR" -path "$PROJECT_DIR/.venv" -prune -o -name __pycache__ -type d -exec rm -rf {} + 2>/dev/null || true

# 1.5.2: video card.  Only when nothing is saved yet; never fails the update.
hw_update_step() {
  [ -f "$PROJECT_DIR/hwsetup.sh" ] || return 0
  say "Video card (hardware transcoding)"
  local cur
  cur="$(cd "$PROJECT_DIR" && run_as "$VENV_PY" -m app.cli hw-get 2>/dev/null | tail -1)"
  if [ -n "$cur" ]; then ok "kept your setting: ${cur}  (Settings > Transcoding)"; return 0; fi
  # shellcheck source=hwsetup.sh
  . "$PROJECT_DIR/hwsetup.sh"
  if [ -n "$SVC_USER" ]; then RUN_AS=(runuser -u "$SVC_USER" --); else RUN_AS=(); fi
  SKIP_APT="no"
  hw_scan
  hw_packages
  hw_groups
  hw_choose update
}
hw_update_step || printf "    \033[33mWARN\033[0m %s\n" "video card setup skipped -- Settings > Transcoding can test it later"

say "Starting $APP_NAME"
restart_and_check "$NEW" || false
trap - ERR

say "Update complete: v${CUR:-?} -> v$NEW"
echo "    Backup of the previous version: $BACKUP"
echo "    Undo:  sudo bash $PROJECT_DIR/update.sh --rollback $BACKUP"
